-- =====================================================================
-- Basis Data Limielle Nail Art
-- 01_skema.sql : tabel, primary key, foreign key, constraint
-- Sumber      : Business_Rule_Limielle v1.1 dan ERD_Limielle (revisi tanpa DP)
-- DBMS        : PostgreSQL 18 (dijalankan lewat psql atau Query Tool pgAdmin 4)
-- =====================================================================

DROP SCHEMA IF EXISTS limielle CASCADE;
CREATE SCHEMA limielle;
SET search_path TO limielle;

-- ---------------------------------------------------------------------
-- PENGGUNA  (Bagian 5) : saat ini hanya Ci Dessy
-- ---------------------------------------------------------------------
CREATE TABLE pengguna (
    id_pengguna   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama          VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- PELANGGAN  (Bagian 1 & 4) : relasi rekursif REFERRAL lewat id_pengajak
-- ---------------------------------------------------------------------
CREATE TABLE pelanggan (
    id_pelanggan  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama          VARCHAR(100) NOT NULL,
    no_telepon    VARCHAR(20)  NOT NULL UNIQUE,
    kode_referral VARCHAR(20)  UNIQUE,              -- diisi otomatis oleh trigger
    id_pengajak   INTEGER REFERENCES pelanggan (id_pelanggan),
    CONSTRAINT ck_pelanggan_tidak_mengajak_diri CHECK (id_pengajak <> id_pelanggan),
    CONSTRAINT ck_pelanggan_telepon CHECK (no_telepon ~ '^[0-9+]{8,20}$')
);

-- ---------------------------------------------------------------------
-- ROYALTY_CARD  (Bagian 4) : 1:1 dengan PELANGGAN
-- ---------------------------------------------------------------------
CREATE TABLE royalty_card (
    id_kartu          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pelanggan      INTEGER NOT NULL UNIQUE
                      REFERENCES pelanggan (id_pelanggan) ON DELETE CASCADE,
    jumlah_kunjungan  INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_kunjungan >= 0)
);

-- ---------------------------------------------------------------------
-- LAYANAN  (Bagian 1)
-- ---------------------------------------------------------------------
CREATE TABLE layanan (
    id_layanan       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_layanan     VARCHAR(100) NOT NULL UNIQUE,
    deskripsi        TEXT,
    harga_acuan      NUMERIC(12,2) NOT NULL CHECK (harga_acuan >= 0),
    durasi_estimasi  INTEGER NOT NULL CHECK (durasi_estimasi > 0)   -- dalam menit
);

-- ---------------------------------------------------------------------
-- BOOKING  (Bagian 2) : tanpa DP
-- waktu_pemesanan = kapan booking dibuat; jadwal layanan ada di TIME_SLOT
-- ---------------------------------------------------------------------
CREATE TABLE booking (
    id_booking       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pelanggan     INTEGER NOT NULL REFERENCES pelanggan (id_pelanggan),
    id_pengguna      INTEGER NOT NULL REFERENCES pengguna (id_pengguna),
    waktu_pemesanan  TIMESTAMP NOT NULL DEFAULT now(),
    status           VARCHAR(25) NOT NULL DEFAULT 'Menunggu Konfirmasi'
                     CHECK (status IN ('Menunggu Konfirmasi','Terkonfirmasi',
                                       'Selesai','Dibatalkan','Tidak Hadir')),
    kanal_booking    VARCHAR(10) NOT NULL DEFAULT 'Online'
                     CHECK (kanal_booking IN ('Online','WhatsApp'))
);

-- DETAIL_BOOKING : composite entity M:N BOOKING - LAYANAN
CREATE TABLE detail_booking (
    id_booking         INTEGER NOT NULL REFERENCES booking (id_booking),
    id_layanan         INTEGER NOT NULL REFERENCES layanan (id_layanan),
    harga_kesepakatan  NUMERIC(12,2) NOT NULL CHECK (harga_kesepakatan >= 0),
    PRIMARY KEY (id_booking, id_layanan)
);

-- ---------------------------------------------------------------------
-- TIME_SLOT  (Bagian 2) : potongan 30 menit; id_booking NULL = slot kosong
-- ---------------------------------------------------------------------
CREATE TABLE time_slot (
    id_slot     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_booking  INTEGER REFERENCES booking (id_booking),
    tanggal     DATE NOT NULL,
    jam_mulai   TIME NOT NULL,
    jam_selesai TIME NOT NULL,
    CONSTRAINT ck_slot_jam CHECK (jam_selesai > jam_mulai),
    CONSTRAINT uq_slot UNIQUE (tanggal, jam_mulai),
    -- dua slot tidak boleh tumpang tindih pada tanggal yang sama
    CONSTRAINT ex_slot_tidak_tumpang_tindih
        EXCLUDE USING gist (tsrange(tanggal + jam_mulai, tanggal + jam_selesai) WITH &&)
);
CREATE INDEX ix_slot_booking ON time_slot (id_booking);

-- ---------------------------------------------------------------------
-- VOUCHER  (Bagian 4) : nilai_potongan dalam persen (contoh narasumber: 10%)
-- [VOU-04/06] berlaku 1 tahun; lewat dari berlaku_sampai = Kedaluwarsa
-- ---------------------------------------------------------------------
CREATE TABLE voucher (
    kode_voucher       VARCHAR(20) PRIMARY KEY,
    id_pelanggan       INTEGER NOT NULL REFERENCES pelanggan (id_pelanggan),
    no_invoice_pemicu  VARCHAR(20) UNIQUE,       -- FK ditambahkan setelah INVOICE dibuat
    nilai_potongan     NUMERIC(5,2) NOT NULL CHECK (nilai_potongan > 0 AND nilai_potongan <= 100),
    dibuat_pada        TIMESTAMP NOT NULL DEFAULT now(),                          -- [DAT-03]
    berlaku_sampai     DATE NOT NULL DEFAULT (current_date + interval '1 year')::date,
    status             VARCHAR(11) NOT NULL DEFAULT 'Tersedia'
                       CHECK (status IN ('Tersedia','Terpakai','Kedaluwarsa'))
);

-- ---------------------------------------------------------------------
-- INVOICE  (Bagian 3)
-- ---------------------------------------------------------------------
CREATE SEQUENCE seq_invoice;

CREATE TABLE invoice (
    no_invoice        VARCHAR(20) PRIMARY KEY
                      DEFAULT ('INV-' || to_char(now(), 'YYYYMM') || '-' ||
                               lpad(nextval('limielle.seq_invoice')::text, 4, '0')),
    id_pelanggan      INTEGER NOT NULL REFERENCES pelanggan (id_pelanggan),
    id_pengguna       INTEGER NOT NULL REFERENCES pengguna (id_pengguna),
    id_booking        INTEGER UNIQUE REFERENCES booking (id_booking),       -- NULL = walk-in
    kode_voucher      VARCHAR(20) UNIQUE REFERENCES voucher (kode_voucher), -- maks. 1 voucher
    tanggal           DATE NOT NULL DEFAULT current_date,
    dibuat_pada       TIMESTAMP NOT NULL DEFAULT now(),                           -- [DAT-03]
    total_tagihan    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_tagihan >= 0),
    potongan_voucher  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (potongan_voucher >= 0),
    status            VARCHAR(12) NOT NULL DEFAULT 'Belum Lunas'
                      CHECK (status IN ('Belum Lunas','Lunas','Dibatalkan'))
);

ALTER TABLE voucher
    ADD CONSTRAINT fk_voucher_invoice_pemicu
    FOREIGN KEY (no_invoice_pemicu) REFERENCES invoice (no_invoice);

-- DETAIL_INVOICE : composite entity M:N INVOICE - LAYANAN
CREATE TABLE detail_invoice (
    no_invoice  VARCHAR(20) NOT NULL REFERENCES invoice (no_invoice),
    id_layanan  INTEGER NOT NULL REFERENCES layanan (id_layanan),
    harga       NUMERIC(12,2) NOT NULL CHECK (harga >= 0),
    jumlah      INTEGER NOT NULL DEFAULT 1 CHECK (jumlah > 0),
    PRIMARY KEY (no_invoice, id_layanan)
);

-- PEMBAYARAN : satu invoice dapat dibayar beberapa kali (mis. tunai + transfer)
CREATE TABLE pembayaran (
    id_pembayaran      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_invoice         VARCHAR(20) NOT NULL REFERENCES invoice (no_invoice),
    tanggal_bayar      TIMESTAMP NOT NULL DEFAULT now(),
    jumlah_bayar       NUMERIC(12,2) NOT NULL CHECK (jumlah_bayar > 0),
    metode_pembayaran  VARCHAR(20) NOT NULL
                       CHECK (metode_pembayaran IN ('Tunai','Transfer Bank','QRIS','E-Wallet','Lainnya')),
    status             VARCHAR(10) NOT NULL DEFAULT 'Diterima'
                       CHECK (status IN ('Diterima','Dibatalkan'))
);

-- ---------------------------------------------------------------------
-- BARANG dan MUTASI_STOK  (Bagian 5, prioritas rendah)
-- ---------------------------------------------------------------------
CREATE TABLE barang (
    id_barang    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_barang  VARCHAR(100) NOT NULL UNIQUE,
    jumlah_stok  INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_stok >= 0)
);

CREATE TABLE mutasi_stok (
    id_mutasi  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_barang  INTEGER NOT NULL REFERENCES barang (id_barang),
    tanggal    DATE NOT NULL DEFAULT current_date,
    jenis      VARCHAR(12) NOT NULL CHECK (jenis IN ('Masuk','Keluar','Penyesuaian')),
    jumlah     INTEGER NOT NULL,
    CONSTRAINT ck_mutasi_jumlah CHECK (
        (jenis IN ('Masuk','Keluar') AND jumlah > 0) OR (jenis = 'Penyesuaian' AND jumlah <> 0))
);
